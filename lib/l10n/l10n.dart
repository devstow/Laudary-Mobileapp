/// Holds the app locale (null = follow system). RTL is automatic for Arabic.
class LocaleController extends ChangeNotifier {
  LocaleController(this._code);
  String? _code; // 'en' | 'ar' | null

  Locale? get locale => _code == null ? null : Locale(_code!);
  String get code => _code ?? 'en';

  void setLanguage(String code) {
    _code = code;
    notifyListeners();
  }
}

